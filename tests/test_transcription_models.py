"""Integration: the real Whisper pipeline (Silero VAD + faster-whisper) on recorded speech.

Uses the small `tiny` model on CPU so it runs on any machine; skipped if it isn't downloaded
(`bayn models` fetches it). Clips: tests/data/*.wav (generated by scripts/make_sample_audio.ps1).
"""

from pathlib import Path

import pytest

from bayn.common.config import TranscriptionConfig
from bayn.transcription.audio_sources import read_wav
from bayn.transcription.engine import WhisperEngine, model_dir, silero_vad
from bayn.transcription.segmenter import Segmenter

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not (model_dir("tiny") / "model.bin").exists(), reason="run `bayn models` (needs tiny)"),
]
DATA = Path(__file__).parent / "data"


@pytest.fixture(scope="module")
def engine():
    return WhisperEngine(TranscriptionConfig(model="tiny", device="cpu"))


def test_english_clip_transcribed(engine):
    r = engine.transcribe(read_wav(DATA / "en_short.wav"), "mixed")
    assert r.language == "en"
    words = r.text.lower()
    assert "write down the time" in words and "episode" in words


def test_arabic_clip_detected_as_arabic(engine):
    """tiny is weak at Arabic spelling, but language detection must be right (GPU model: word-perfect)."""
    r = engine.transcribe(read_wav(DATA / "ar_short.wav"), "mixed")
    assert r.language == "ar"
    assert any("؀" <= ch <= "ۿ" for ch in r.text)       # Arabic script


def test_silero_vad_segments_the_mixed_demo(engine):
    audio = read_wav(Path(__file__).parents[1] / "samples" / "audio" / "demo.wav")
    seg = Segmenter(silero_vad(), min_silence_s=0.6)
    utts = []
    for i in range(0, len(audio), 1600):
        seg.feed(audio[i:i + 1600], 1_800_000_000.0 + i / 16000)
        utts += seg.step().finals
    utts += seg.flush()
    assert 7 <= len(utts) <= 20                                   # 7 sentences, some split at pauses
    langs = [engine.transcribe(u.audio, "mixed").language for u in utts]
    assert set(langs) == {"en", "ar"}                             # both languages detected
